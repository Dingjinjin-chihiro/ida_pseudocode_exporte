def get_pseudocode(ea: int) -> str:
    """
    仅提取纯文本，不手工调用 cfunc.release()。

    cfunc_t 是 SWIG / 引用计数包装对象。为了降低长时间批量运行时的
    生命周期风险，文本提取完成后仅让 Python 引用离开作用域，再由
    cleanup_hexrays_cache() 主动清理 Hex-Rays 缓存。
    """
    cfunc = ida_hexrays.decompile(ea)
    if cfunc is None:
        raise RuntimeError("Hex-Rays 未返回伪代码。")
    lines: List[str] = []
    for line in cfunc.get_pseudocode():
        try:
            lines.append(ida_lines.tag_remove(line.line))
        except Exception as exc:
            lines.append(f"// [伪代码行转换失败：{exc!r}]")
    return "\n".join(lines).rstrip() + "\n"


def decompile_with_retry(target: ExportTarget, cfg: dict) -> str:
    try:
        return get_pseudocode(target.start_ea)
    except Exception:
        if not cfg["retry_failed_after_local_analysis"]:
            raise
        ida_auto.auto_wait_range(target.start_ea, target.end_ea)
        return get_pseudocode(target.start_ea)


def cleanup_hexrays_cache(target_ea: Optional[int], processed_count: int, cfg: dict, logger: Logger = default_logger, force_all: bool = False) -> None:
    if not cfg.get("stable_mode", True):
        return
    if target_ea is not None and cfg.get("clear_target_cache_after_each_function", True):
        try:
            ida_hexrays.mark_cfunc_dirty(int(target_ea), False)
        except Exception as exc:
            logger(f"警告：清理函数缓存 0x{int(target_ea):X} 失败：{exc}")
    interval = int(cfg.get("clear_all_cache_interval", 0) or 0)
    if force_all or (interval > 0 and processed_count > 0 and processed_count % interval == 0):
        try:
            ida_hexrays.clear_cached_cfuncs()
        except Exception as exc:
            logger(f"警告：清理全部 Hex-Rays 缓存失败：{exc}")
    gc_interval = int(cfg.get("python_gc_interval", 0) or 0)
    if force_all or (gc_interval > 0 and processed_count > 0 and processed_count % gc_interval == 0):
        gc.collect()
    cooldown = int(cfg.get("cooldown_milliseconds", 0) or 0)
    if cooldown > 0:
        time.sleep(cooldown / 1000.0)


def choose_run_dir(cfg: dict) -> Tuple[Path, Path]:
    """创建运行目录。路径过深时自动切换到短路径目录。"""
    resume = str(cfg.get("resume_run_dir") or "").strip()
    if resume:
        run_dir = Path(resume)
        run_dir.mkdir(parents=True, exist_ok=True)
    else:
        requested_root = Path(cfg["output_dir"]) if str(cfg.get("output_dir") or "").strip() else get_default_output_root()
        run_name = f"run_{timestamp_id()}"
        desired_run_dir = requested_root / run_name
        probe = desired_run_dir / "functions" / "_short" / "batch_none" / "0000000000000000_0000000000.c"
        if cfg.get("auto_compact_root_on_overflow", True) and not path_fits_budget(probe, cfg):
            compact_root = get_compact_storage_root(requested_root, cfg)
            run_dir = compact_root / run_name
            write_redirect_note(requested_root, run_dir, run_name)
        else:
            run_dir = desired_run_dir
        run_dir.mkdir(parents=True, exist_ok=True)
        try:
            (run_dir / "requested_output_root.txt").write_text(
                f"用户选择的输出根目录：{requested_root}\n实际运行目录：{run_dir}\n",
                encoding="utf-8",
            )
        except Exception:
            pass
    attempt_dir = run_dir / "attempts" / f"attempt_{timestamp_id()}"
    attempt_dir.mkdir(parents=True, exist_ok=True)
    return run_dir, attempt_dir


def resolve_function_root(run_dir: Path, cfg: dict) -> Path:
    """确保函数文件根目录足够短；必要时自动重定向到短路径存储目录。"""

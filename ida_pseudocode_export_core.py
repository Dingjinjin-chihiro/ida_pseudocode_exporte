@dataclass(frozen=True)
class ExportTarget:
    start_ea: int
    end_ea: int
    raw_name: str
    display_name: str
    segment_name: str
    flags: int

    @property
    def length(self) -> int:
        return max(0, self.end_ea - self.start_ea)

    def to_json(self) -> dict:
        return {
            "start_ea": self.start_ea,
            "end_ea": self.end_ea,
            "raw_name": self.raw_name,
            "display_name": self.display_name,
            "segment_name": self.segment_name,
            "flags": self.flags,
            "length": self.length,
        }

    @staticmethod
    def from_json(data: dict) -> "ExportTarget":
        return ExportTarget(
            int(data["start_ea"]), int(data["end_ea"]), str(data["raw_name"]),
            str(data.get("display_name") or data["raw_name"]), str(data.get("segment_name") or ""),
            int(data.get("flags", 0)),
        )



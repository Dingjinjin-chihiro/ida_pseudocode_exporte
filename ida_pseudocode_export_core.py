def split_text_list(text: str) -> List[str]:
    return [item.strip() for item in re.split(r"[;\r\n]+", text or "") if item.strip()]


def deduplicate_strings(values: Iterable[str]) -> List[str]:
    result: List[str] = []
    seen: Set[str] = set()
    for value in values:
        item = str(value).strip()
        if not item or item in seen:
            continue
        seen.add(item)
        result.append(item)
    return result


def normalize_list(value) -> List[str]:
    if isinstance(value, str):
        return deduplicate_strings(split_text_list(value))
    if isinstance(value, (list, tuple, set)):
        return deduplicate_strings(value)
    return []


def parse_integer(value, default: int = 0) -> int:
    if isinstance(value, int):
        return value
    raw = str(value or "").strip()
    if not raw:
        return default
    try:
        return int(raw, 0)
    except ValueError:
        try:
            return int(raw, 16)
        except ValueError:
            return default


def deep_merge_config(base: dict, override: dict) -> dict:
    result = dict(base)
    for key, value in override.items():
        if key in result:
            result[key] = value
    return result


def normalize_config(cfg: dict) -> dict:
    merged = deep_merge_config(DEFAULT_CONFIG, cfg or {})
    for key in LIST_CONFIG_KEYS:
        merged[key] = normalize_list(merged.get(key, []))
    int_keys = (
        "maximum_dependency_depth", "minimum_function_length", "maximum_function_length",
        "maximum_export_count", "maximum_full_path_length", "maximum_readable_name_length",
        "progress_update_interval", "flush_interval", "clear_all_cache_interval",
        "python_gc_interval", "cooldown_milliseconds", "maximum_functions_per_session",
        "class_folder_component_length", "functions_per_batch_folder",
        "internal_path_budget_override",
    )
    for key in int_keys:
        merged[key] = parse_integer(merged.get(key, DEFAULT_CONFIG[key]), int(DEFAULT_CONFIG[key]))
    for key in int_keys:
        merged[key] = max(0, int(merged[key]))
    # 路径预算由平台和输出根目录自动决定。旧版 maximum_full_path_length 仅作为兼容字段保留。
    merged["maximum_full_path_length"] = max(0, merged["maximum_full_path_length"])
    merged["internal_path_budget_override"] = max(0, merged["internal_path_budget_override"])
    merged["progress_update_interval"] = max(1, merged["progress_update_interval"])
    merged["flush_interval"] = max(1, merged["flush_interval"])
    merged["class_folder_component_length"] = max(16, merged["class_folder_component_length"])
    merged["functions_per_batch_folder"] = max(1, merged["functions_per_batch_folder"])
    if merged.get("filename_mode") == "short_hash":
        merged["filename_mode"] = "auto_readable"
    if merged.get("scope") not in {key for key, _ in SCOPE_OPTIONS}:
        merged["scope"] = "all_internal"
    if merged.get("filename_mode") not in {key for key, _ in FILENAME_OPTIONS}:
        merged["filename_mode"] = "auto_readable"
    if merged.get("ui_theme") not in {"follow_ida", "soft_dark", "soft_gray"}:
        merged["ui_theme"] = "soft_dark"
    merged["config_schema_version"] = CONFIG_SCHEMA_VERSION
    return merged


def validate_regex(pattern: str, label: str, case_sensitive: bool) -> None:
    if not pattern:
        return
    try:
        re.compile(pattern, 0 if case_sensitive else re.IGNORECASE)
    except re.error as exc:
        raise RuntimeError(f"{label}不是有效正则表达式：{exc}") from exc


def has_include_filters(cfg: dict) -> bool:
    return bool(cfg["include_exact_names"] or cfg["include_prefixes"] or cfg["include_contains"] or cfg["include_globs"] or cfg["include_regex"])


def validate_config(cfg: dict) -> None:
    validate_regex(cfg["include_regex"], "包含正则表达式", cfg["case_sensitive_filters"])
    validate_regex(cfg["exclude_regex"], "排除正则表达式", cfg["case_sensitive_filters"])
    if cfg["maximum_function_length"] and cfg["minimum_function_length"] > cfg["maximum_function_length"]:
        raise RuntimeError("最小函数长度不能大于最大函数长度。")
    if cfg["scope"].startswith("range_"):
        start, end = parse_integer(cfg["range_start"]), parse_integer(cfg["range_end"])
        if start <= 0 or end <= start:
            raise RuntimeError("地址范围无效，请填写正确的起始地址和结束地址。")
    if cfg["scope"].startswith("matched_") and not has_include_filters(cfg):
        raise RuntimeError("按名称匹配导出时，至少填写一种包含条件。")


def load_json(path: Path) -> dict:
    if not path.is_file():
        return {}
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    return data if isinstance(data, dict) else {}


def atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    try:
        temp.write_text(text, encoding="utf-8", errors="replace")
        os.replace(str(temp), str(path))
    finally:
        try:
            if temp.exists():
                temp.unlink()
        except Exception:
            pass


def atomic_write_json(path: Path, data: object) -> None:
    atomic_write_text(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def append_jsonl(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(data, ensure_ascii=False) + "\n")
        f.flush()


def try_demangle(name: str) -> str:
    try:
        return idc.demangle_name(name, idc.get_inf_attr(idc.INF_SHORT_DN)) or ""
    except Exception:
        return ""


def symbol_names(raw_name: str) -> Tuple[str, ...]:
    demangled = try_demangle(raw_name)
    return (raw_name, demangled) if demangled and demangled != raw_name else (raw_name,)


def normalize_match_values(values: Iterable[str], case_sensitive: bool) -> Tuple[str, ...]:
    return tuple(values) if case_sensitive else tuple(value.lower() for value in values)


def exact_matches(names: Iterable[str], patterns: Sequence[str], case_sensitive: bool) -> bool:
    if not patterns:
        return False
    return bool(set(normalize_match_values(names, case_sensitive)) & set(normalize_match_values(patterns, case_sensitive)))


def starts_with_any(names: Iterable[str], patterns: Sequence[str], case_sensitive: bool) -> bool:
    if not patterns:
        return False
    normalized_patterns = normalize_match_values(patterns, case_sensitive)
    return any(name.startswith(normalized_patterns) for name in normalize_match_values(names, case_sensitive))


def contains_any(names: Iterable[str], patterns: Sequence[str], case_sensitive: bool) -> bool:
    if not patterns:
        return False
    ns, ps = normalize_match_values(names, case_sensitive), normalize_match_values(patterns, case_sensitive)
    return any(pattern in name for name in ns for pattern in ps)


def glob_matches(names: Iterable[str], patterns: Sequence[str], case_sensitive: bool) -> bool:
    if not patterns:
        return False
    ns, ps = normalize_match_values(names, case_sensitive), normalize_match_values(patterns, case_sensitive)
    return any(fnmatch.fnmatchcase(name, pattern) for name in ns for pattern in ps)


def regex_matches(names: Iterable[str], pattern: str, case_sensitive: bool) -> bool:
    if not pattern:
        return False
    regex = re.compile(pattern, 0 if case_sensitive else re.IGNORECASE)
    return any(regex.search(name) is not None for name in names)


def matches_include_filters(names: Iterable[str], cfg: dict) -> bool:
    cs = cfg["case_sensitive_filters"]
    return (
        exact_matches(names, cfg["include_exact_names"], cs)
        or starts_with_any(names, cfg["include_prefixes"], cs)
        or contains_any(names, cfg["include_contains"], cs)
        or glob_matches(names, cfg["include_globs"], cs)
        or regex_matches(names, cfg["include_regex"], cs)
    )


def matches_exclude_filters(names: Iterable[str], cfg: dict) -> Optional[str]:
    cs = cfg["case_sensitive_filters"]
    if exact_matches(names, cfg["exclude_exact_names"], cs):
        return "命中自定义排除精确名称"
    if starts_with_any(names, cfg["exclude_prefixes"], cs):
        return "命中自定义排除前缀"
    if contains_any(names, cfg["exclude_contains"], cs):
        return "命中自定义排除子串"
    if glob_matches(names, cfg["exclude_globs"], cs):
        return "命中自定义排除通配符"
    if regex_matches(names, cfg["exclude_regex"], cs):
        return "命中自定义排除正则表达式"
    return None


def segment_matches(name: str, patterns: Sequence[str]) -> bool:
    if not patterns:
        return False
    lowered = name.lower()
    return any(fnmatch.fnmatchcase(lowered, pattern.lower()) for pattern in patterns)


def is_standard_cpp(names: Iterable[str]) -> bool:
    return any(name.startswith(STANDARD_LIBRARY_PREFIXES) or name.startswith(STANDARD_LIBRARY_MANGLED_PREFIXES) for name in names)


def is_common_c(names: Iterable[str]) -> bool:
    for name in names:
        stripped = name.strip()
        variants = {stripped, stripped.lstrip("_")}
        if stripped.startswith("__imp_"):
            variants.add(stripped[len("__imp_"):].lstrip("_"))
        if variants & COMMON_C_LIBRARY_NAMES:
            return True
    return False


def is_runtime(names: Iterable[str]) -> bool:
    return any(name.strip() in RUNTIME_EXACT_NAMES or name.strip().startswith(RUNTIME_PREFIXES) for name in names)


def is_third_party(names: Iterable[str]) -> bool:
    return any(name.startswith(KNOWN_THIRD_PARTY_PREFIXES) for name in names)


def is_autogenerated(name: str) -> bool:
    return bool(re.match(r"^(sub_|nullsub_|loc_|j_|unknown_)", name))



def collect_import_addresses(logger: Logger = default_logger) -> Set[int]:
    addresses: Set[int] = set()
    try:
        module_count = int(ida_nalt.get_import_module_qty())
    except Exception:
        return addresses

    def callback(ea, name, ordinal):
        addresses.add(int(ea))
        return True

    for module_index in range(module_count):
        try:
            ida_nalt.enum_import_names(module_index, callback)
        except Exception as exc:
            logger(f"警告：枚举导入模块 {module_index} 失败：{exc}")
    return addresses


def classify_skip(func, import_addresses: Set[int], cfg: dict) -> Optional[str]:
    ea = int(func.start_ea)
    raw_name = ida_funcs.get_func_name(ea) or f"sub_{ea:X}"
    names = symbol_names(raw_name)
    segment_name = get_segment_name(ea)
    segment = ida_segment.getseg(ea)
    if segment is None:
        return "缺少所属段信息"
    if cfg["skip_external_segments"]:
        external_type = getattr(ida_segment, "SEG_XTRN", None)
        if external_type is not None and int(segment.type) == int(external_type):
            return "外部段函数"
    if cfg["skip_non_executable_segments"]:
        exec_permission = int(getattr(ida_segment, "SEGPERM_EXEC", 1))
        if int(segment.perm) & exec_permission == 0:
            return "不可执行段函数"
    if cfg["skip_imported_functions"] and ea in import_addresses:
        return "导入函数"
    if cfg["skip_ida_library_functions"] and int(func.flags) & int(ida_funcs.FUNC_LIB):
        return "IDA 库签名识别函数"
    if cfg["skip_thunks"] and int(func.flags) & int(ida_funcs.FUNC_THUNK):
        return "跳板函数（thunk）"
    if cfg["include_segments"] and not segment_matches(segment_name, cfg["include_segments"]):
        return "所属段不在包含列表中"
    if segment_matches(segment_name, cfg["exclude_segments"]):
        return "所属段已被排除"
    force_include = starts_with_any(names, cfg["force_include_prefixes"], cfg["case_sensitive_filters"])
    if not force_include:
        custom_reason = matches_exclude_filters(names, cfg)
        if custom_reason:
            return custom_reason
        if cfg["skip_standard_cpp_names"] and is_standard_cpp(names):
            return "C++ 标准库函数名称"
        if cfg["skip_common_c_names"] and is_common_c(names):
            return "常见 C 标准库函数名称"
        if cfg["skip_runtime_helpers"] and is_runtime(names):
            return "编译器或运行时辅助函数"
        if cfg["skip_known_third_party_names"] and is_third_party(names):
            return "已知第三方模块函数名称"
        if cfg["skip_autogenerated_names"] and is_autogenerated(raw_name):
            return "IDA 自动生成函数名称"
    length = int(func.end_ea) - int(func.start_ea)
    if cfg["minimum_function_length"] and length < cfg["minimum_function_length"]:
        return f"函数长度 0x{length:X} 小于最小限制 0x{cfg['minimum_function_length']:X}"
    if cfg["maximum_function_length"] and length > cfg["maximum_function_length"]:
        return f"函数长度 0x{length:X} 超过最大限制 0x{cfg['maximum_function_length']:X}"
    return None


def collect_retained_pool(import_addresses: Set[int], cfg: dict) -> Tuple[Dict[int, ExportTarget], List[SkippedTarget]]:
    retained: Dict[int, ExportTarget] = {}
    skipped: List[SkippedTarget] = []
    seen: Set[int] = set()
    for candidate_ea in idautils.Functions():
        func = ida_funcs.get_func(candidate_ea)
        if func is None:
            continue
        start_ea = int(func.start_ea)
        if start_ea in seen:
            continue
        seen.add(start_ea)
        raw_name = ida_funcs.get_func_name(start_ea) or f"sub_{start_ea:X}"
        segment_name = get_segment_name(start_ea)
        reason = classify_skip(func, import_addresses, cfg)
        if reason:
            skipped.append(SkippedTarget(start_ea, raw_name, segment_name, reason))
            continue
        demangled = try_demangle(raw_name)
        retained[start_ea] = ExportTarget(start_ea, int(func.end_ea), raw_name, demangled or raw_name, segment_name, int(func.flags))
    return retained, sorted(skipped, key=lambda item: item.start_ea)


def collect_direct_dependencies(ea: int, retained: Dict[int, ExportTarget], cache: Dict[int, Set[int]]) -> Set[int]:
    if ea in cache:
        return cache[ea]
    deps: Set[int] = set()
    try:
        items = idautils.FuncItems(ea)
    except Exception:
        cache[ea] = deps
        return deps
    for item_ea in items:
        try:
            refs = idautils.CodeRefsFrom(item_ea, False)
        except Exception:
            continue
        for ref_ea in refs:
            try:
                func = ida_funcs.get_func(ref_ea)
            except Exception:
                func = None
            if func is None:
                continue
            callee = int(func.start_ea)
            if callee != ea and callee in retained:
                deps.add(callee)
    cache[ea] = deps
    return deps


def expand_dependencies(roots: Iterable[int], retained: Dict[int, ExportTarget], maximum_depth: int) -> Tuple[Set[int], Set[Tuple[int, int]]]:
    selected: Set[int] = set()
    edges: Set[Tuple[int, int]] = set()
    cache: Dict[int, Set[int]] = {}
    queue = deque()
    for ea in roots:
        if ea in retained and ea not in selected:
            selected.add(ea)
            queue.append((ea, 0))
    while queue:
        caller, depth = queue.popleft()
        if maximum_depth and depth >= maximum_depth:
            continue
        for callee in collect_direct_dependencies(caller, retained, cache):
            edges.add((caller, callee))
            if callee not in selected:
                selected.add(callee)
                queue.append((callee, depth + 1))
    return selected, edges


def resolve_scope_targets(retained: Dict[int, ExportTarget], cfg: dict) -> Tuple[List[ExportTarget], int, Set[Tuple[int, int]]]:
    scope = cfg["scope"]
    if scope == "all_internal":
        targets = sorted(retained.values(), key=lambda item: item.start_ea)
        return targets, len(targets), set()
    roots: Set[int]
    if scope.startswith("matched_"):
        roots = {ea for ea, target in retained.items() if matches_include_filters(symbol_names(target.raw_name), cfg)}
    elif scope.startswith("current_"):
        current_func = ida_funcs.get_func(int(ida_kernwin.get_screen_ea()))
        if current_func is None:
            raise RuntimeError("当前光标不在 IDA 已识别函数内部。")
        start_ea = int(current_func.start_ea)
        if start_ea not in retained:
            raise RuntimeError("当前函数已被筛选条件排除。")
        roots = {start_ea}
    elif scope.startswith("range_"):
        start, end = parse_integer(cfg["range_start"]), parse_integer(cfg["range_end"])
        roots = {ea for ea, target in retained.items() if target.start_ea < end and target.end_ea > start}
    else:
        raise RuntimeError(f"不支持的导出范围：{scope}")
    root_count = len(roots)
    if scope.endswith("_with_dependencies"):
        selected, edges = expand_dependencies(roots, retained, cfg["maximum_dependency_depth"])
    else:
        selected, edges = roots, set()
    targets = sorted((retained[ea] for ea in selected), key=lambda item: item.start_ea)
    return targets, root_count, edges


def sanitize_filename_component(value: str) -> str:
    safe = re.sub(r'[<>:"/\\|?*\x00-\x1F]', "_", value)
    safe = re.sub(r"\s+", "_", safe.strip(" .")) or "unnamed"
    return f"_{safe}" if safe.upper() in WINDOWS_RESERVED_NAMES else safe


def get_auto_path_budget(cfg: dict) -> int:
    """返回内部安全路径预算。普通用户无需填写路径长度。"""
    override = int(cfg.get("internal_path_budget_override", 0) or 0)
    if override > 0:
        return max(160, override)
    # Windows 兼容预算偏保守，避免旧环境或未启用长路径策略时失败。
    return 238 if os.name == "nt" else 1024


def path_fits_budget(path: Path, cfg: dict, reserve: int = 0) -> bool:
    return len(str(path)) + int(reserve) <= get_auto_path_budget(cfg)


def get_compact_storage_root(seed_path: Path, cfg: dict) -> Path:
    """在用户选择的目录过深时自动选择短路径存储根目录。"""
    configured = str(cfg.get("compact_output_root") or "").strip()
    digest = hashlib.sha1(str(seed_path).encode("utf-8", errors="replace")).hexdigest()[:10]
    candidates: List[Path] = []
    if configured:
        candidates.append(Path(configured) / digest)
    if os.name == "nt":
        anchor = Path(seed_path.anchor) if seed_path.anchor else Path.cwd().anchor
        if str(anchor):
            candidates.append(Path(anchor) / "IDAExport" / digest)
    candidates.append(Path(tempfile.gettempdir()) / "IDAExport" / digest)
    for candidate in candidates:
        try:
            candidate.mkdir(parents=True, exist_ok=True)
            return candidate
        except Exception:
            continue
    raise RuntimeError("无法自动创建短路径输出目录。请将输出根目录改为较短且可写的位置。")



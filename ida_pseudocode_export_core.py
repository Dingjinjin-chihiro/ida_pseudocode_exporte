def collect_all_function_name_records(logger: Logger = default_logger) -> List[dict]:
    import_addresses = collect_import_addresses(logger)
    records: List[dict] = []
    for index, ea in enumerate(idautils.Functions(), start=1):
        func = ida_funcs.get_func(ea)
        if func is None:
            continue
        start_ea = int(func.start_ea)
        end_ea = int(func.end_ea)
        raw_name = ida_funcs.get_func_name(start_ea) or f"sub_{start_ea:X}"
        demangled_name = try_demangle(raw_name)
        flags = int(func.flags)
        records.append({
            "index": len(records) + 1,
            "address": f"0x{start_ea:X}",
            "start_ea": start_ea,
            "end_ea": end_ea,
            "length": max(0, end_ea - start_ea),
            "segment": get_segment_name(start_ea),
            "raw_name": raw_name,
            "demangled_name": demangled_name,
            "display_name": demangled_name or raw_name,
            "flags": flags,
            "flags_hex": f"0x{flags:X}",
            "is_library": bool(flags & int(ida_funcs.FUNC_LIB)),
            "is_thunk": bool(flags & int(ida_funcs.FUNC_THUNK)),
            "is_import_name": start_ea in import_addresses,
        })
    records.sort(key=lambda item: int(item["start_ea"]))
    for index, item in enumerate(records, start=1):
        item["index"] = index
    return records


